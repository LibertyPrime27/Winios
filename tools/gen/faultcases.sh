#!/bin/sh
# Generate tests/difftest/faultcases_gen.inc: short x86-64 sequences that end
# in a memory access which will fault, each with enough live state before it
# that recovering the guest registers from a compiled block is a real test.
#
# The bytes are committed so CI and the device builds need no x86 assembler.
# Each case carries its own disassembly as a comment, from objdump, so the
# table can be read and checked without reassembling anything.
#
#   sh tools/gen/faultcases.sh > tests/difftest/faultcases_gen.inc
set -e
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

# r15 holds an address inside the unmapped page; r14 an address just above it,
# in mapped memory, for the cases that walk a stack into the hole. The
# instructions before the access exist to put guest state in host registers:
# the more that is live and unspilled at the fault, the more the recovery has
# to get right.
cat > "$tmp/cases.txt" <<'EOF'
load|a plain load, several GPRs dirty|add %rax,%rbx; sub %rcx,%rdx; xor %rsi,%rsi; mov (%r15),%rsi
load32|a 32-bit load, which is kept zero-extended|add %eax,%ebx; imul %ecx,%edx; mov (%r15),%esi
load8|an 8-bit load into the low byte|add %rax,%rbx; movb (%r15),%cl
load16|a 16-bit load|sub %rax,%rbx; movw (%r15),%cx
loadsx|a sign-extending load|add %rax,%rbx; movslq (%r15),%rcx
store|a store, the value register dirty|add %rax,%rbx; mov %rbx,(%r15)
store8|an 8-bit store|add %rax,%rbx; movb %bl,(%r15)
rmw|read-modify-write: the fault is on the load half|add %rax,%rbx; add %rbx,(%r15)
rmw_store|read-modify-write where only the store faults is not expressible, so this is the whole op|xor %rax,%rax; or %rax,(%r15)
index|a scaled-index address, index register dirty|add %rax,%rbx; mov $3,%rcx; mov 8(%r15,%rcx,4),%rdx
lea_then_load|the address computed into a dirty register first|add %rax,%rbx; lea 16(%r15),%rcx; mov (%rcx),%rdx
push|push onto a faulting stack: the SP is decremented before the store|add %rax,%rbx; mov %r15,%rsp; push %rbx
pop|pop from a faulting stack|add %rax,%rbx; mov %r15,%rsp; pop %rcx
push_two|two pushes, the second faults after the first moved the SP|add %rax,%rbx; mov %r14,%rsp; push %rbx; push %rcx
call_mem|an indirect call whose target load faults|add %rax,%rbx; call *(%r15)
xchg_mem|an exchange with memory|add %rax,%rbx; xchg %rcx,(%r15)
cmpxchg_mem|a compare-exchange with memory|add %rax,%rbx; cmpxchg %rcx,(%r15)
neg_mem|a read-modify-write that also writes flags|add %rax,%rbx; negq (%r15)
inc_mem|an increment in memory, which writes all flags but CF|add %rax,%rbx; incq (%r15)
sse_load|an SSE load with several XMMs dirty|addpd %xmm2,%xmm3; mulpd %xmm4,%xmm5; movups (%r15),%xmm6
sse_load_sd|a scalar double load|addsd %xmm2,%xmm3; movsd (%r15),%xmm4
sse_store|an SSE store|addpd %xmm2,%xmm3; movups %xmm3,(%r15)
sse_store_sd|a scalar double store|mulsd %xmm2,%xmm3; movsd %xmm3,(%r15)
mixed|GPRs, XMMs and the stack all live at the fault|add %rax,%rbx; addpd %xmm2,%xmm3; sub %rcx,%rdx; mulsd %xmm4,%xmm5; mov (%r15),%rsi
after_call|the access follows a callout, which invalidates the register cache|add %rax,%rbx; cpuid; add %rcx,%rdx; mov (%r15),%rsi
EOF

cat > "$tmp/x87.txt" <<'EOF'
x87_load|an x87 load with a loaded stack|fldl (%rdi); fldl 8(%rdi); faddp; fldl (%r15)
x87_load_s|a 32-bit x87 load|fldl (%rdi); flds (%r15)
x87_store|an x87 store|fldl (%rdi); fldl 8(%rdi); fmulp; fstpl (%r15)
x87_store_s|a 32-bit x87 store|fldl (%rdi); fstps (%r15)
x87_load_int|an integer x87 load|fldl (%rdi); fildl (%r15)
x87_store_int|an integer x87 store|fldl (%rdi); fldl 8(%rdi); faddp; fistpl (%r15)
x87_deep|four values on the x87 stack at the fault|fldl (%rdi); fldl 8(%rdi); fldl 16(%rdi); fldl 24(%rdi); fldl (%r15)
EOF

emit() {   # file x87flag
    while IFS='|' read -r name why insns; do
        [ -n "$name" ] || continue
        printf '.text\n' > "$tmp/a.s"
        printf '%s\n' "$insns" | tr ';' '\n' >> "$tmp/a.s"
        gcc -c -x assembler "$tmp/a.s" -o "$tmp/a.o"
        objdump -d --no-show-raw-insn "$tmp/a.o" | sed -n 's/^ *[0-9a-f]*:\t//p' | sed 's/  */ /g; s/ *$//' > "$tmp/dis.txt"
        bytes=$(objdump -d "$tmp/a.o" | sed -n 's/^ *[0-9a-f]*:\t\([0-9a-f ]*\)\t.*/\1/p' | tr -d ' \n' | sed 's/../0x&,/g' | sed 's/,$//')
        # how many instructions come before the faulting one -- the test runs
        # the interpreter exactly that far to get the state a fault must report
        before=$(($(wc -l < "$tmp/dis.txt") - 1))
        printf '    /* %s\n' "$why"
        sed 's/^/     *   /' "$tmp/dis.txt"
        printf '     */\n'
        printf '    { "%s", %d, %d, B(%s), sizeof(B(%s)) },\n' "$name" "$2" "$before" "$bytes" "$bytes"
    done < "$1"
}

printf '/* Generated by tools/gen/faultcases.sh -- do not edit.\n'
printf ' *\n'
printf ' * Sequences that end in a faulting memory access, with live state before\n'
printf ' * it. r15 points into the unmapped page, r14 just above it, rdi at\n'
printf ' * readable data. The number after the x87 flag is how many instructions\n'
printf ' * run before the faulting one.\n'
printf ' */\n'
printf 'static const faultcase FAULTCASES[] = {\n'
emit "$tmp/cases.txt" 0
emit "$tmp/x87.txt" 1
printf '};\n'

#!/bin/sh
# Generate win32/vtables_gen.h: COM vtable slot numbers, straight out of
# mingw-w64's own headers.
#
# A COM interface is an array of function pointers and the *order* is the ABI.
# Getting one slot wrong does not fail to compile and does not fail a test
# that never calls it -- it calls whatever is next in the table, which is how
# the missing IDirect3DDevice9::CreateDepthStencilSurface showed up as
# "unimplemented slot 57". Counting them by hand once is a mistake waiting to
# happen; counting them by hand for every new interface is a certainty.
#
# So the slots become named constants and the C tables index by name. A table
# in the wrong order still compiles, but a table with the wrong *name* in a
# slot cannot, and a missing slot leaves an obvious hole.
#
#   sh tools/gen/vtables.sh > win32/vtables_gen.h
set -e
cd "$(dirname "$0")/../.."
INC=${MINGW_INCLUDE:-/usr/share/mingw-w64/include}

# header|interface|prefix
SPECS='dsound.h|IDirectSound8|DS8
dsound.h|IDirectSoundBuffer8|DSB8
dsound.h|IDirectSound3DListener|DS3L
dsound.h|IDirectSound3DBuffer|DS3B
dsound.h|IDirectSoundNotify|DSN
dsound.h|IDirectSoundCapture|DSC
dsound.h|IDirectSoundCaptureBuffer8|DSCB8
dinput.h|IDirectInput8W|DI8
dinput.h|IDirectInput7W|DI7
dinput.h|IDirectInputDevice8W|DID8
dinput.h|IDirectInputDevice7W|DID7'

printf '/* Generated by tools/gen/vtables.sh from mingw-w64 headers -- do not edit.\n'
printf ' *\n'
printf ' * COM vtable slot numbers. The order is the ABI: a table built with one\n'
printf ' * slot out calls whatever is next in it, which compiles, links, and runs\n'
printf ' * wrong. Indexing by these names instead of by literal numbers means the\n'
printf ' * order comes from the header rather than from counting.\n'
printf ' */\n'
printf '#ifndef W32_VTABLES_GEN_H\n#define W32_VTABLES_GEN_H\n'

echo "$SPECS" | while IFS='|' read -r hdr iface prefix; do
    [ -n "$iface" ] || continue
    MINGW_HDR="$INC/$hdr" IFACE="$iface" PREFIX="$prefix" python3 - <<'PY'
import os, re, sys
src = open(os.environ['MINGW_HDR'], errors='ignore').read()
iface, prefix = os.environ['IFACE'], os.environ['PREFIX']
m = re.search(r'DECLARE_INTERFACE_?\(\s*' + iface + r'\s*(?:,\s*\w+\s*)?\)\s*\{(.*?)\n\};', src, re.S)
if not m:
    sys.stderr.write("vtables.sh: %s not found in %s\n" % (iface, os.environ['MINGW_HDR']))
    sys.exit(1)
body = m.group(1)
# STDMETHOD(Name)(...)  and  STDMETHOD_(Type,Name)(...)
names = [a or b for a, b in re.findall(
    r'STDMETHOD_\(\s*\w+\s*,\s*(\w+)\s*\)|STDMETHOD\(\s*(\w+)\s*\)', body)]
print("\n/* %s -- %d slots */" % (iface, len(names)))
print("enum {")
for i, n in enumerate(names):
    print("    %s_%s = %d," % (prefix, n, i))
print("    %s_NSLOTS = %d," % (prefix, len(names)))
print("};")
PY
done

printf '\n#endif\n'

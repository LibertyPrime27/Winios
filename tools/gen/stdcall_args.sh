#!/bin/sh
# Regenerate win32/stdcall_args.c from mingw-w64's import libraries.
#
# An import table gives a name, not an argument count -- but on x86 a stdcall
# callee pops its own arguments, so returning from a function we have not
# implemented needs to know how many bytes to pop. Guess wrong and the stack
# is corrupt; refuse to guess and one missing function ends the run.
#
# mingw's import libraries carry the answer: they decorate stdcall imports as
# _Name@bytes. This lifts that into a table so an unimplemented import can
# return cleanly and the program can carry on to show us what else it needs.
#
#   apt install gcc-mingw-w64-i686   # then run this from the repo root
set -e
LIB=${LIB:-/usr/i686-w64-mingw32/lib}
DLLS="kernel32 user32 gdi32 advapi32 winmm ole32 oleaut32 shell32 shlwapi comdlg32
      version winspool ws2_32 wininet comctl32 imm32 dinput8 dsound d3d9 psapi setupapi
      iphlpapi crypt32 rpcrt4 userenv secur32 netapi32 mpr avicap32 msimg32 opengl32"
out=win32/stdcall_args.c
{
  for d in $DLLS; do
    [ -f "$LIB/lib$d.a" ] || continue
    i686-w64-mingw32-nm "$LIB/lib$d.a" 2>/dev/null |
      sed -n 's/.*__imp__\([A-Za-z0-9_]*\)@\([0-9]*\)$/\1 \2/p'
  done
} | sort -u -k1,1 > /tmp/stdcall.txt
n=$(wc -l < /tmp/stdcall.txt)
{
  echo "/* Generated by tools/gen/stdcall_args.sh -- do not edit."
  echo " *"
  echo " * How many bytes of arguments a stdcall function pops on x86, for the"
  echo " * Win32 functions we do not implement. An import table gives a name and"
  echo " * nothing else; without this, returning from an unimplemented import would"
  echo " * either corrupt the stack or not be possible at all, and the first missing"
  echo " * function would end every run. With it, the call is logged, zero is"
  echo " * returned, the stack is left correct, and the program carries on to show"
  echo " * what else it needs."
  echo " *"
  echo " * Lifted from mingw-w64's import libraries, which decorate stdcall imports"
  echo " * as _Name@bytes. $n functions, sorted, binary-searched."
  echo " */"
  echo "#include <stdint.h>"
  echo "#include <string.h>"
  echo
  echo "typedef struct { const char *name; uint16_t bytes; } stdcall_arg;"
  echo "static const stdcall_arg g_stdcall[] = {"
  awk '{printf "    { \"%s\", %s },\n", $1, $2}' /tmp/stdcall.txt
  echo "};"
  cat <<'CEOF'

/* -1 when we have never heard of it, which the caller must treat as "cannot
 * safely return" rather than "zero arguments". */
int w32_stdcall_bytes(const char *name) {
    int lo = 0, hi = (int)(sizeof g_stdcall / sizeof g_stdcall[0]) - 1;
    while (lo <= hi) {
        int mid = lo + (hi - lo) / 2;
        int c = strcmp(g_stdcall[mid].name, name);
        if (c == 0) return g_stdcall[mid].bytes;
        if (c < 0) lo = mid + 1; else hi = mid - 1;
    }
    return -1;
}
CEOF
} > $out
echo "wrote $out: $n functions"

/* XAudio2: the sound API of every game since 2008 or so.
 *
 * A game creates an engine, one mastering voice, and a source voice per
 * sound, then *submits buffers* to a source voice and is told through a
 * callback when each one has been played -- which is how it streams music
 * and knows when to hand over the next block. So the shape here is a queue
 * per voice, fed into audio_out's gapless two-block slot: the block playing
 * and the one behind it are the mixer's, the rest wait here, and at every
 * tick (a wait, or any call in) what the mixer has finished is popped and the
 * game's OnBufferEnd/OnLoopEnd/OnStreamEnd are called on the guest thread,
 * where the guest is.
 *
 * Two vtable layouts. 2.7 (xaudio2_7.dll, reached through CoCreateInstance
 * with one of the 2.x CLSIDs) has GetDeviceCount, GetDeviceDetails and
 * Initialize after Release, a two-argument GetState and no GetChannelMask;
 * 2.8 and 2.9 (XAudio2Create from xaudio2_8/9.dll) do not. The slot
 * numbers below come from Wine's xaudio2.idl -- the header is generated by
 * widl in a shape tools/gen/vtables.sh cannot read -- and the counts are
 * asserted against what that file declares.
 *
 * Not here: effects (APOs), submix routing beyond pass-through, output
 * matrices, filters, ADPCM/xWMA formats. Each answers with the documented
 * code or S_OK-and-nothing, never by pretending to have done something that
 * would be heard.
 */
#define _GNU_SOURCE
#include "w32.h"
#include <math.h>
#include <stdio.h>
#include <string.h>


static void build_tables(void) {
    if (g_built) return;
    g_built = 1;
    for (int i = 0; i < XA7_NSLOTS; i++) xa7_m[i] = (w32_api){ 0, 0, 0, 0, 0 };
    for (int i = 0; i < XA9_NSLOTS; i++) xa9_m[i] = (w32_api){ 0, 0, 0, 0, 0 };
    for (int i = 0; i < XS_NSLOTS; i++)  src_m[i]  = (w32_api){ 0, 0, 0, 0, 0 };
    for (int i = 0; i < XV_NSLOTS; i++)  sub_m[i]  = (w32_api){ 0, 0, 0, 0, 0 };
    for (int i = 0; i < XM7_NSLOTS; i++) mas7_m[i] = (w32_api){ 0, 0, 0, 0, 0 };
    for (int i = 0; i < XM9_NSLOTS; i++) mas9_m[i] = (w32_api){ 0, 0, 0, 0, 0 };
    w32_api *e[2] = { xa7_m, xa9_m };
    for (int t = 0; t < 2; t++) {
        int o = t == 0 ? 3 : 0;                    /* 2.7's three extra slots */
        M(e[t], XA_QueryInterface, "QueryInterface", 3, w32_com_QueryInterface);
        M(e[t], XA_AddRef, "AddRef", 1, w32_com_AddRef);
        M(e[t], XA_Release, "Release", 1, w32_com_Release);
        M(e[t], XA9_RegisterForCallbacks + o, "RegisterForCallbacks", 2, e_ok);
        M(e[t], XA9_UnregisterForCallbacks + o, "UnregisterForCallbacks", 2, e_void);
        M(e[t], XA9_CreateSourceVoice + o, "CreateSourceVoice", 8, e_CreateSourceVoice);
        M(e[t], XA9_CreateSubmixVoice + o, "CreateSubmixVoice", 8, e_CreateSubmixVoice);
        M(e[t], XA9_CreateMasteringVoice + o, "CreateMasteringVoice", t == 0 ? 7 : 8, e_CreateMasteringVoice);
        M(e[t], XA9_StartEngine + o, "StartEngine", 1, e_StartEngine);
        M(e[t], XA9_StopEngine + o, "StopEngine", 1, e_StopEngine);
        M(e[t], XA9_CommitChanges + o, "CommitChanges", 2, e_ok);
        M(e[t], XA9_GetPerformanceData + o, "GetPerformanceData", 2, e_GetPerformanceData);
        M(e[t], XA9_SetDebugConfiguration + o, "SetDebugConfiguration", 3, e_void);
    }
    M(xa7_m, XA7_GetDeviceCount, "GetDeviceCount", 2, e7_GetDeviceCount);
    M(xa7_m, XA7_GetDeviceDetails, "GetDeviceDetails", 3, e7_GetDeviceDetails);
    M(xa7_m, XA7_Initialize, "Initialize", 3, e_ok);
    voice_common(src_m, 1); voice_common(sub_m, 0); voice_common(mas7_m, 0); voice_common(mas9_m, 0);
    M(src_m, XS_Start, "Start", 3, s_Start);
    M(src_m, XS_Stop, "Stop", 3, s_Stop);
    M(src_m, XS_SubmitSourceBuffer, "SubmitSourceBuffer", 3, s_SubmitSourceBuffer);
    M(src_m, XS_FlushSourceBuffers, "FlushSourceBuffers", 1, s_FlushSourceBuffers);
    M(src_m, XS_Discontinuity, "Discontinuity", 1, v_ok);
    M(src_m, XS_ExitLoop, "ExitLoop", 2, s_ExitLoop);
    M(src_m, XS_GetState, "GetState", 3, s_GetState);          /* 2.7's GetState has two arguments; see cls_src7 below */
    M(src_m, XS_SetFrequencyRatio, "SetFrequencyRatio", 3, s_SetFrequencyRatio);
    M(src_m, XS_GetFrequencyRatio, "GetFrequencyRatio", 2, s_GetFrequencyRatio);
    M(src_m, XS_SetSourceSampleRate, "SetSourceSampleRate", 2, s_SetSourceSampleRate);
    M(mas9_m, XM9_GetChannelMask, "GetChannelMask", 2, m_GetChannelMask);
    /* A 2.7 source voice differs in one slot's argument count -- GetState has
     * no Flags -- which on x86 is the number of bytes to pop. Its own table. */
    memcpy(src7_m, src_m, sizeof src7_m);
    M(src7_m, XS_GetState, "GetState", 2, s_GetState);
    cls_src7 = (w32_com_class){ "IXAudio2SourceVoice (2.7)", src7_m, XS_NSLOTS, TAG_XA2V, 0, {0} };
    cls_xa7  = (w32_com_class){ "IXAudio2 (2.7)",          xa7_m,  XA7_NSLOTS, TAG_XA2,  0, {0} };
    cls_xa9  = (w32_com_class){ "IXAudio2",                xa9_m,  XA9_NSLOTS, TAG_XA2,  0, {0} };
    cls_src  = (w32_com_class){ "IXAudio2SourceVoice",     src_m,  XS_NSLOTS,  TAG_XA2V, 0, {0} };
    cls_sub  = (w32_com_class){ "IXAudio2SubmixVoice",     sub_m,  XV_NSLOTS,  TAG_XA2V, 0, {0} };
    cls_mas7 = (w32_com_class){ "IXAudio2MasteringVoice (2.7)", mas7_m, XM7_NSLOTS, TAG_XA2V, 0, {0} };
    cls_mas9 = (w32_com_class){ "IXAudio2MasteringVoice",  mas9_m, XM9_NSLOTS, TAG_XA2V, 0, {0} };
}
static uint64_t make_engine(w32 *w, int ver) {
    build_tables();
    uint64_t o = w32_com_new(w, ver >= 8 ? &cls_xa9 : &cls_xa7, E_NFIELDS);
    if (o) { w32_com_set(w, o, E_VER, (uint64_t)ver); w32_com_set(w, o, E_RUNNING, 1); }
    return o;
}


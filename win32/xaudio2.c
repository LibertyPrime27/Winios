/* IXAudio2VoiceCallback */
enum { CB_OnVoiceProcessingPassStart = 0, CB_OnVoiceProcessingPassEnd, CB_OnStreamEnd, CB_OnBufferStart, CB_OnBufferEnd,
       CB_OnLoopEnd, CB_OnVoiceError };

/* Engine fields, voice fields (64-bit slots) */
enum { E_VER = 0, E_RUNNING = 1, E_NFIELDS = 2 };
enum { V_KIND = 0, V_VER = 1, V_SLOT = 2, V_CB = 3, V_ENGINE = 4, V_NFIELDS = 5 };
enum { KIND_SOURCE = 1, KIND_SUBMIX = 2, KIND_MASTER = 3 };
enum { TAG_XA2 = 0x58410000, TAG_XA2V };
enum { MAX_VOICE = 64, QLEN = 64 };

/* One sub-block the mixer can play in one go: a buffer's play region, or one
 * pass of its loop region. */
typedef struct {
    const uint8_t *mem; uint32_t bytes;
    uint64_t ctx;
    int first, last;                 /* first/last sub-block of its XAUDIO2_BUFFER */
    int loop, loop_forever, eos;
} blk;
typedef struct {
    int      used, started;
    uint64_t obj;                    /* the voice object */
    int      src;                    /* mixer source id, or -1 until the first buffer */
    uint32_t freq, channels, bits; int is_float;
    float    volume, ratio, master;
    blk      q[QLEN]; int head, n;
    int      in_mixer;               /* how many of the front blocks the mixer holds (0..2) */
    uint64_t submitted, ended;       /* buffers, for BuffersQueued */
} voice;
static voice g_v[MAX_VOICE];
static float g_master = 1.0f;
static w32_com_class cls_xa7, cls_xa9, cls_src, cls_src7, cls_sub, cls_mas7, cls_mas9;
static w32_api xa7_m[XA7_NSLOTS], xa9_m[XA9_NSLOTS], src_m[XS_NSLOTS], src7_m[XS_NSLOTS], sub_m[XV_NSLOTS], mas7_m[XM7_NSLOTS], mas9_m[XM9_NSLOTS];
static int g_built;

static int32_t lin_to_mB(float v) {
    if (v <= 0.0f) return -10000;
    if (v >= 1.0f) return 0;
    double mB = 2000.0 * log10((double)v);
    return mB < -10000 ? -10000 : (int32_t)mB;
}
static uint32_t frame_bytes(const voice *v) { return (v->channels ? v->channels : 1) * ((v->bits ? v->bits : 16) / 8); }

/* --- callbacks into the game -------------------------------------------------- */
static void call_cb(w32 *w, uint64_t cb, int slot, int nargs, uint64_t a1, uint64_t a2) {
    if (!cb || w->exited) return;
    int psz = (int)w32_ptrsize(w);
    uint64_t vt = w32_read(w, cb, psz);
    if (!vt) return;
    uint64_t fn = w32_read(w, vt + (uint64_t)psz * (uint32_t)slot, psz);
    if (!fn) return;
    uint64_t args[3] = { cb, a1, a2 };
    w32_call_guest(w, fn, nargs, args);
}

/* --- the queue and the mixer ---------------------------------------------------- */
static void src_fill(const voice *v, const blk *b, w32_audio_src *s) {
    memset(s, 0, sizeof *s);
    s->mem = b->mem; s->size = b->bytes;
    s->freq = (uint32_t)((float)v->freq * (v->ratio > 0 ? v->ratio : 1.0f));
    s->channels = v->channels; s->bits = v->bits; s->is_float = v->is_float;
    s->playing = v->started; s->looping = b->loop_forever;
    s->vol_mB = lin_to_mB(v->volume * v->master * g_master);
}
/* Hand the mixer what it can take: the front block as current if it has
 * nothing, the second as its next. */
static void refill(w32 *w, voice *v) {
    (void)w;
    while (v->in_mixer < 2 && v->in_mixer < v->n) {
        blk *b = &v->q[(v->head + v->in_mixer) % QLEN];
        w32_audio_src s; src_fill(v, b, &s);
        if (v->src < 0) { v->src = w32_audio_src_add(&s); if (v->src < 0) return; }
        else if (v->in_mixer == 0) w32_audio_src_set(v->src, &s);
        else if (!w32_audio_src_queue_next(v->src, &s)) return;
        v->in_mixer++;
    }
    if (v->started && v->src >= 0) w32_audio_open();
}
static void voice_sync(voice *v) {
    if (v->src < 0 || v->in_mixer == 0) return;
    w32_audio_src s; src_fill(v, &v->q[v->head % QLEN], &s);
    w32_audio_src_set(v->src, &s);
}
/* What the mixer finished since last time: pop, tell the game, refill. */
static void voice_tick(w32 *w, voice *v) {
    if (v->src < 0) return;
    int ended = w32_audio_src_take_ended(v->src);
    uint64_t cb = w32_com_get(w, v->obj, V_CB);
    while (ended-- > 0 && v->n > 0) {
        blk done = v->q[v->head % QLEN];
        v->head++; v->n--; if (v->in_mixer > 0) v->in_mixer--;
        if (done.loop && !done.last) call_cb(w, cb, CB_OnLoopEnd, 2, done.ctx, 0);
        if (done.last) { v->ended++; call_cb(w, cb, CB_OnBufferEnd, 2, done.ctx, 0); }
        if (v->n > 0 && v->q[v->head % QLEN].first) call_cb(w, cb, CB_OnBufferStart, 2, v->q[v->head % QLEN].ctx, 0);
        if (done.last && done.eos && v->n == 0) call_cb(w, cb, CB_OnStreamEnd, 1, 0, 0);
        if (w->exited) return;
    }
    refill(w, v);
}
static int g_in_tick;
void w32_xaudio2_tick(w32 *w) {
    if (!g_built || g_in_tick) return;
    g_in_tick = 1;
    w32_audio_pump();
    for (int i = 0; i < MAX_VOICE && !w->exited; i++) if (g_v[i].used) voice_tick(w, &g_v[i]);
    g_in_tick = 0;
}

/* --- the voice --------------------------------------------------------------- */
static voice *voice_of(w32 *w, uint64_t obj) {
    int i = (int)w32_com_get(w, obj, V_SLOT) - 1;
    return i >= 0 && i < MAX_VOICE && g_v[i].used ? &g_v[i] : 0;
}
static void v_GetVoiceDetails(w32 *w) {
    uint64_t p = ARG(1); int ver = (int)w32_com_get(w, ARG(0), V_VER);
    voice *v = voice_of(w, ARG(0));
    if (!p || !w32_mem_ok(w, p, ver >= 8 ? 16 : 12)) { RET((uint64_t)(uint32_t)E_INVALIDARG_); return; }
    uint64_t at = p;
    w32_write(w, at, 4, 0); at += 4;                                  /* CreationFlags */
    if (ver >= 8) { w32_write(w, at, 4, 0); at += 4; }                /* ActiveFlags */
    w32_write(w, at, 4, v ? v->channels : 2); w32_write(w, at + 4, 4, v ? v->freq : 44100);
    RET(S_OK_);
}
static void v_ok(w32 *w) { (void)w; RET(S_OK_); }
static void v_unsupported(w32 *w) { (void)w; RET((uint64_t)(uint32_t)E_NOTIMPL_); }
static void v_SetVolume(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    float f = w32_fargf(w, 1);
    if (f < 0) f = 0;
    if (v) {
        if (v->src < 0 && (int)w32_com_get(w, ARG(0), V_KIND) == KIND_MASTER) g_master = f;
        v->volume = f; voice_sync(v);
        if ((int)w32_com_get(w, ARG(0), V_KIND) == KIND_MASTER) {   /* every source hears the master */
            g_master = f;
            for (int i = 0; i < MAX_VOICE; i++) if (g_v[i].used) voice_sync(&g_v[i]);
        }
    }
    RET(S_OK_);
}
static void v_GetVolume(w32 *w) {
    voice *v = voice_of(w, ARG(0)); float f = v ? v->volume : 1.0f; uint32_t bits; memcpy(&bits, &f, 4);
    if (ARG(1)) w32_write(w, ARG(1), 4, bits);
    RET(0);
}
static void v_GetChannelVolumes(w32 *w) {
    voice *v = voice_of(w, ARG(0)); float f = v ? v->volume : 1.0f; uint32_t bits; memcpy(&bits, &f, 4);
    uint32_t n = (uint32_t)ARG(1);
    if (ARG(2) && n <= 8 && w32_mem_ok(w, ARG(2), 4ull * n)) for (uint32_t i = 0; i < n; i++) w32_write(w, ARG(2) + 4ull * i, 4, bits);
    RET(0);
}
static void v_GetOutputMatrix(w32 *w) {
    uint32_t sc = (uint32_t)ARG(2), dc = (uint32_t)ARG(3); float one = 1.0f; uint32_t bits; memcpy(&bits, &one, 4);
    if (ARG(4) && sc * dc <= 64 && w32_mem_ok(w, ARG(4), 4ull * sc * dc))
        for (uint32_t i = 0; i < sc * dc; i++) w32_write(w, ARG(4) + 4ull * i, 4, (i % (sc + 1)) == 0 ? bits : 0);
    RET(0);
}
static void v_DestroyVoice(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (v) { if (v->src >= 0) w32_audio_src_remove(v->src); memset(v, 0, sizeof *v); }
    w32_com_set(w, ARG(0), V_SLOT, 0);
    RET(0);
}
static void v_GetEffectState(w32 *w) { if (ARG(2)) w32_write(w, ARG(2), 4, 0); RET(0); }
static void v_GetFilterParameters(w32 *w) {
    /* XAUDIO2_FILTER_PARAMETERS { Type; Frequency; OneOverQ }: a low-pass at the top, Q 1 -- the default */
    float freq = 1.0f, q = 1.0f; uint32_t fb, qb; memcpy(&fb, &freq, 4); memcpy(&qb, &q, 4);
    uint64_t p = ARG(1);
    if (p && w32_mem_ok(w, p, 12)) { w32_write(w, p, 4, 0); w32_write(w, p + 4, 4, fb); w32_write(w, p + 8, 4, qb); }
    RET(0);
}
static void v_GetOutputFilterParameters(w32 *w) {
    float freq = 1.0f, q = 1.0f; uint32_t fb, qb; memcpy(&fb, &freq, 4); memcpy(&qb, &q, 4);
    uint64_t p = ARG(2);
    if (p && w32_mem_ok(w, p, 12)) { w32_write(w, p, 4, 0); w32_write(w, p + 4, 4, fb); w32_write(w, p + 8, 4, qb); }
    RET(0);
}

/* source voice */
static void s_Start(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (!v) { RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return; }
    int was = v->started;
    v->started = 1; voice_sync(v); refill(w, v);
    if (v->src >= 0) w32_audio_open();
    if (!was && v->n > 0 && v->q[v->head % QLEN].first) call_cb(w, w32_com_get(w, ARG(0), V_CB), CB_OnBufferStart, 2, v->q[v->head % QLEN].ctx, 0);
    RET(S_OK_);
}
static void s_Stop(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (v) { v->started = 0; voice_sync(v); }
    RET(S_OK_);
}
/* XAUDIO2_BUFFER: Flags, AudioBytes, pAudioData, PlayBegin, PlayLength, LoopBegin,
 * LoopLength, LoopCount, pContext -- the pointers pad it differently per bitness. */
static void s_SubmitSourceBuffer(w32 *w) {
    voice *v = voice_of(w, ARG(0)); uint64_t b = ARG(1); int psz = (int)w32_ptrsize(w);
    if (!v) { RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return; }
    if (!b || !w32_mem_ok(w, b, psz == 4 ? 36 : 48)) { RET((uint64_t)(uint32_t)E_INVALIDARG_); return; }
    uint32_t flags = (uint32_t)w32_read(w, b, 4), bytes = (uint32_t)w32_read(w, b + 4, 4);
    uint64_t data = w32_read(w, b + 8, psz), o = psz == 4 ? 12 : 16;
    uint32_t begin = (uint32_t)w32_read(w, b + o, 4), len = (uint32_t)w32_read(w, b + o + 4, 4);
    uint32_t lbegin = (uint32_t)w32_read(w, b + o + 8, 4), llen = (uint32_t)w32_read(w, b + o + 12, 4), lcount = (uint32_t)w32_read(w, b + o + 16, 4);
    uint64_t ctx = w32_read(w, b + (psz == 4 ? 32 : 40), psz);
    uint32_t fb = frame_bytes(v), total = fb ? bytes / fb : 0;
    const uint8_t *mem = W32PN(w, data, bytes);
    if (!mem || !total) { RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return; }
    if (begin >= total) begin = 0;
    if (!len || begin + len > total) len = total - begin;
    /* the play region once, then the loop region as many times as asked */
    int nblk = 1 + (lcount ? (lcount == XAUDIO2_LOOP_INFINITE_ ? 1 : (int)(lcount > 8 ? 8 : lcount)) : 0);
    if (v->n + nblk > QLEN) { RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return; }
    blk *first = &v->q[(v->head + v->n) % QLEN];
    memset(first, 0, sizeof *first);
    first->mem = mem + (uint64_t)begin * fb; first->bytes = len * fb; first->ctx = ctx; first->first = 1;
    first->last = nblk == 1; first->eos = (flags & XAUDIO2_END_OF_STREAM_) != 0;
    v->n++;
    if (lcount) {
        if (lbegin >= total) lbegin = begin;
        if (!llen || lbegin + llen > total) llen = total - lbegin;
        for (int k = 1; k < nblk; k++) {
            blk *l = &v->q[(v->head + v->n) % QLEN];
            memset(l, 0, sizeof *l);
            l->mem = mem + (uint64_t)lbegin * fb; l->bytes = llen * fb; l->ctx = ctx; l->loop = 1;
            l->loop_forever = lcount == XAUDIO2_LOOP_INFINITE_;
            l->last = k == nblk - 1; l->eos = first->eos;
            v->n++;
        }
    }
    v->submitted++;
    int was_empty = v->in_mixer == 0;
    refill(w, v);
    if (was_empty && v->started) call_cb(w, w32_com_get(w, ARG(0), V_CB), CB_OnBufferStart, 2, ctx, 0);
    RET(S_OK_);
}
static void s_FlushSourceBuffers(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (!v) { RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return; }
    uint64_t cb = w32_com_get(w, ARG(0), V_CB);
    /* everything behind the block playing goes, and each buffer it belonged to
     * is reported ended; a stopped voice has nothing playing, so it loses the
     * head as well */
    int keep = v->started && v->in_mixer > 0 ? 1 : 0;
    if (v->src >= 0 && v->in_mixer > 1) w32_audio_src_clear_next(v->src);
    if (v->src >= 0 && !keep && v->in_mixer > 0) { w32_audio_src s; src_fill(v, &v->q[v->head % QLEN], &s); s.playing = 0; s.mem = 0; s.size = 0; w32_audio_src_set(v->src, &s); }
    while (v->n > keep) {
        blk gone = v->q[(v->head + v->n - 1) % QLEN];
        v->n--;
        if (gone.last) { v->ended++; call_cb(w, cb, CB_OnBufferEnd, 2, gone.ctx, 0); }
    }
    v->in_mixer = keep;
    RET(S_OK_);
}
static void s_ExitLoop(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (v && v->n > 0) {
        blk *cur = &v->q[v->head % QLEN];
        if (cur->loop_forever) { cur->loop_forever = 0; cur->last = 1; voice_sync(v); }
        /* drop the remaining loop passes of the current buffer */
        int keep = 1;
        while (v->n > keep && v->q[(v->head + keep) % QLEN].loop && !v->q[(v->head + keep) % QLEN].first) {
            v->q[(v->head + keep) % QLEN] = v->q[(v->head + v->n - 1) % QLEN]; v->n--;   /* not order-preserving past the loop; nothing follows a loop pass but its own siblings */
        }
        v->q[v->head % QLEN].last = 1;
        if (v->in_mixer > 1) { w32_audio_src_clear_next(v->src); v->in_mixer = 1; }
    }
    RET(S_OK_);
}
/* XAUDIO2_VOICE_STATE { pCurrentBufferContext; BuffersQueued; SamplesPlayed } */
static void s_GetState(w32 *w) {
    voice *v = voice_of(w, ARG(0)); uint64_t p = ARG(1); int psz = (int)w32_ptrsize(w);
    w32_xaudio2_tick(w);
    if (!p || !w32_mem_ok(w, p, psz == 4 ? 16 : 24)) { RET(0); return; }
    uint64_t ctx = 0; uint32_t queued = 0; uint64_t played = 0;
    if (v) {
        for (int i = 0; i < v->n; i++) if (v->q[(v->head + i) % QLEN].first) queued++;
        if (v->n > 0) { ctx = v->q[v->head % QLEN].ctx; if (!v->q[v->head % QLEN].first) queued++; }
        if (v->src >= 0) played = w32_audio_src_frames_done(v->src);
    }
    w32_write(w, p, psz, ctx);
    w32_write(w, p + psz, 4, queued);
    w32_write(w, p + (psz == 4 ? 8 : 16), 8, played);
    RET(0);
}
static void s_SetFrequencyRatio(w32 *w) {
    voice *v = voice_of(w, ARG(0)); float r = w32_fargf(w, 1);
    if (r < 1.0f / 1024) r = 1.0f / 1024; if (r > 1024.0f) r = 1024.0f;
    if (v) { v->ratio = r; voice_sync(v); }
    RET(S_OK_);
}
static void s_GetFrequencyRatio(w32 *w) {
    voice *v = voice_of(w, ARG(0)); float r = v ? v->ratio : 1.0f; uint32_t bits; memcpy(&bits, &r, 4);
    if (ARG(1)) w32_write(w, ARG(1), 4, bits);
    RET(0);
}
static void s_SetSourceSampleRate(w32 *w) {
    voice *v = voice_of(w, ARG(0));
    if (v && ARG(1)) { v->freq = (uint32_t)ARG(1); voice_sync(v); }
    RET(S_OK_);
}
static void m_GetChannelMask(w32 *w) { if (ARG(1)) w32_write(w, ARG(1), 4, 3); RET(S_OK_); }   /* SPEAKER_FRONT_LEFT | RIGHT */

/* --- the engine ----------------------------------------------------------------- */
static uint64_t make_voice(w32 *w, int kind, int ver, uint64_t engine) {
    int slot = -1;
    for (int i = 0; i < MAX_VOICE; i++) if (!g_v[i].used) { slot = i; break; }
    if (slot < 0) return 0;
    w32_com_class *cls = kind == KIND_SOURCE ? (ver >= 8 ? &cls_src : &cls_src7) : kind == KIND_SUBMIX ? &cls_sub : ver >= 8 ? &cls_mas9 : &cls_mas7;
    uint64_t o = w32_com_new(w, cls, V_NFIELDS);
    if (!o) return 0;
    voice *v = &g_v[slot];
    memset(v, 0, sizeof *v);
    v->used = 1; v->obj = o; v->src = -1; v->volume = 1.0f; v->ratio = 1.0f; v->master = 1.0f;
    v->freq = 44100; v->channels = 2; v->bits = 16;
    w32_com_set(w, o, V_KIND, (uint64_t)kind); w32_com_set(w, o, V_VER, (uint64_t)ver);
    w32_com_set(w, o, V_SLOT, (uint64_t)slot + 1); w32_com_set(w, o, V_ENGINE, engine);
    return o;
}
/* CreateSourceVoice(ppVoice, pFormat, Flags, MaxFrequencyRatio, pCallback, pSendList, pEffectChain) */
static void e_CreateSourceVoice(w32 *w) {
    uint64_t out = ARG(1), fmt = ARG(2), cb = ARG(4); int ver = (int)w32_com_get(w, ARG(0), E_VER);
    if (!out) { RET((uint64_t)(uint32_t)E_POINTER_); return; }
    if (!fmt || !w32_mem_ok(w, fmt, 16)) { RET((uint64_t)(uint32_t)E_INVALIDARG_); return; }
    uint32_t tag = (uint32_t)w32_read(w, fmt, 2), ch = (uint32_t)w32_read(w, fmt + 2, 2), rate = (uint32_t)w32_read(w, fmt + 4, 4), bits = (uint32_t)w32_read(w, fmt + 14, 2);
    if (tag == 0xFFFE && w32_mem_ok(w, fmt, 40)) tag = (uint32_t)w32_read(w, fmt + 24, 2);
    if ((tag != 1 && tag != 3) || !ch || !rate || !bits) {
        static char note[96]; snprintf(note, sizeof note, "xaudio2!CreateSourceVoice (format tag %u: only PCM and float are decoded here)", tag);
        w32_note_refused(w, note);
        w32_write(w, out, (int)w32_ptrsize(w), 0);
        RET((uint64_t)(uint32_t)XAUDIO2_E_INVALID_CALL_); return;
    }
    uint64_t o = make_voice(w, KIND_SOURCE, ver, ARG(0));
    if (!o) { RET((uint64_t)(uint32_t)E_FAIL_); return; }
    voice *v = voice_of(w, o);
    v->freq = rate; v->channels = ch; v->bits = bits; v->is_float = tag == 3; v->master = g_master;
    w32_com_set(w, o, V_CB, cb);
    w32_write(w, out, (int)w32_ptrsize(w), o);
    if (w->verbose) fprintf(stderr, "winrun: xaudio2: source voice %u Hz, %u ch, %u bit%s%s\n", rate, ch, bits, v->is_float ? " float" : "", cb ? ", with callback" : "");
    RET(S_OK_);
}
